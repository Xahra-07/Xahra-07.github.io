function drawRipples() {
  rCtx.clearRect(0, 0, rCanvas.width, rCanvas.height);
  const isLight = document.body.classList.contains('light-theme');

  ripples.forEach((r, idx) => {
    r.r += r.speed;
    r.alpha = 1 - (r.r / r.maxR);

    if (r.r >= r.maxR) {
      ripples.splice(idx, 1);
      return;
    }

    rCtx.beginPath();
    rCtx.arc(r.x, r.y, r.r, 0, Math.PI * 2);
    // Draw outer rings fading out
    rCtx.strokeStyle = isLight ? `rgba(1, 0, 102, ${r.alpha * 0.35})` : `rgba(203, 161, 53, ${r.alpha * 0.35})`;
    rCtx.lineWidth = 1.5;
    rCtx.stroke();

    // Optional second inner ring for liquid thickness
    if (r.r > 15) {
      rCtx.beginPath();
      rCtx.arc(r.x, r.y, r.r - 10, 0, Math.PI * 2);
      rCtx.strokeStyle = isLight ? `rgba(1, 0, 102, ${r.alpha * 0.15})` : `rgba(203, 161, 53, ${r.alpha * 0.15})`;
      rCtx.lineWidth = 0.8;
      rCtx.stroke();
    }
  });

  requestAnimationFrame(drawRipples);
}

