const fsSource = `
  precision mediump float;
  uniform float uTime;
  uniform vec2 uRes;
  uniform float uLightTheme;
  uniform float uTrackFocus; // changes color parameters depending on active track

  vec2 hash2(vec2 p) {
    p = vec2(dot(p, vec2(127.1, 311.7)), dot(p, vec2(269.5, 183.3)));
    return -1.0 + 2.0 * fract(sin(p) * 43758.5453);
  }

  float voronoi(vec2 p, float t) {
    vec2 n = floor(p);
    vec2 f = fract(p);
    float d1 = 9.0;
    float d2 = 9.0;
    for(int x = -2; x <= 2; x++) {
      for(int y = -2; y <= 2; y++) {
        vec2 g = vec2(float(x), float(y));
        vec2 o = hash2(n + g);
        o = 0.5 + 0.5 * sin(t + 6.283 * o);
        vec2 r = g + o - f;
        float d = dot(r, r);
        if(d < d1) { d2 = d1; d1 = d; }
        else if(d < d2) { d2 = d; }
      }
    }
    return sqrt(d2) - sqrt(d1);
  }

  void main() {
    vec2 uv = gl_FragCoord.xy / uRes;
    float aspect = uRes.x / uRes.y;
    vec2 st = vec2(uv.x * aspect, uv.y);

    // Deep water colors: adjusts depending on track focus
    vec3 deepDark = mix(vec3(0.0, 0.0, 0.08), vec3(0.0, 0.04, 0.12), uTrackFocus);
    vec3 midWater = mix(vec3(0.004, 0.0, 0.25), vec3(0.0, 0.08, 0.35), uTrackFocus);
    
    // Light mode bases (white edges, soft blue center)
    vec3 deepLight = vec3(1.0, 1.0, 1.0);
    vec3 midLight  = vec3(0.83, 0.92, 0.97);

    vec3 deep = mix(deepDark, deepLight, uLightTheme);
    vec3 mid  = mix(midWater, midLight, uLightTheme);

    // Caustic textures
    float c1 = voronoi(st * 2.5, uTime * 0.3);
    float c2 = voronoi(st * 5.0 + vec2(2.0, 1.5), uTime * 0.45);
    float c3 = voronoi(st * 8.5 + vec2(1.0, 3.0), uTime * 0.2);

    float caustic = c1 * 0.5 + c2 * 0.35 + c3 * 0.15;
    caustic = pow(max(caustic, 0.0), 2.0);

    // Caustic colors
    vec3 goldLight = mix(vec3(0.796, 0.631, 0.208), vec3(0.627, 0.471, 0.062), uLightTheme);
    vec3 whiteGlow = mix(vec3(1.0, 0.95, 0.85), vec3(1.0, 1.0, 1.0), uLightTheme);

    vec3 color = mix(mid, deep, uv.y * 0.8);
    color += goldLight * caustic * mix(0.18, 0.26, uTrackFocus);
    color += whiteGlow * caustic * caustic * 0.1;

    // Surface lighting
    float surface = (1.0 - uv.y) * (1.0 - uv.y) * 0.05;
    color += mix(vec3(0.1, 0.15, 0.35), vec3(0.05, 0.05, 0.1), uLightTheme) * surface;

    // Vignette
    vec2 vig = uv - 0.5;
    vig.x *= aspect;
    float d = dot(vig, vig) * 0.65;
    
    vec3 colorDarkVignette = color * clamp(1.0 - d, 0.0, 1.0);
    vec3 colorLightVignette = mix(color, vec3(1.0), clamp(d * 1.5, 0.0, 1.0));
    color = mix(colorDarkVignette, colorLightVignette, uLightTheme);

    gl_FragColor = vec4(color, 1.0);
  }
`;

function createShader(gl, type, src) {
  const s = gl.createShader(type);
  gl.shaderSource(s, src);
  gl.compileShader(s);
  if (!gl.getShaderParameter(s, gl.COMPILE_STATUS)) {
    console.error(gl.getShaderInfoLog(s));
  }
  return s;
}

let glProgram, uTime, uRes, uLightTheme, uTrackFocus;

function initGL() {
  if (!gl) return;

  const vs = createShader(gl, gl.VERTEX_SHADER, vsSource);
  const fs = createShader(gl, gl.FRAGMENT_SHADER, fsSource);
  glProgram = gl.createProgram();
  gl.attachShader(glProgram, vs);
  gl.attachShader(glProgram, fs);
  gl.linkProgram(glProgram);
  gl.useProgram(glProgram);

  const quad = new Float32Array([-1,-1, 1,-1, -1,1, 1,1]);
  const buf = gl.createBuffer();
  gl.bindBuffer(gl.ARRAY_BUFFER, buf);
  gl.bufferData(gl.ARRAY_BUFFER, quad, gl.STATIC_DRAW);

  const aPos = gl.getAttribLocation(glProgram, 'aPos');
  gl.enableVertexAttribArray(aPos);
  gl.vertexAttribPointer(aPos, 2, gl.FLOAT, false, 0, 0);

  uTime = gl.getUniformLocation(glProgram, 'uTime');
  uRes  = gl.getUniformLocation(glProgram, 'uRes');
  uLightTheme = gl.getUniformLocation(glProgram, 'uLightTheme');
  uTrackFocus = gl.getUniformLocation(glProgram, 'uTrackFocus');

  function resize() {
    canvas.width  = window.innerWidth;
    canvas.height = window.innerHeight;
    gl.viewport(0, 0, canvas.width, canvas.height);
  }

  window.addEventListener('resize', resize);
  resize();

  let targetTrackFocus = 0.0;
  let currentTrackFocus = 0.0;

  function draw(ts) {
    const t = ts * 0.001;
    
    // Interpolate track focus variable for smooth changes
    targetTrackFocus = activeTrack === 'all' ? 0.0 : (activeTrack === 'ai' ? 0.4 : (activeTrack === 'design' ? 0.8 : 1.0));
    currentTrackFocus += (targetTrackFocus - currentTrackFocus) * 0.05;

    gl.uniform1f(uTime, t);
    gl.uniform2f(uRes, canvas.width, canvas.height);
    gl.uniform1f(uLightTheme, document.body.classList.contains('light-theme') ? 1.0 : 0.0);
    gl.uniform1f(uTrackFocus, currentTrackFocus);
    
    gl.drawArrays(gl.TRIANGLE_STRIP, 0, 4);
    requestAnimationFrame(draw);
  }
  requestAnimationFrame(draw);
}

initGL();


