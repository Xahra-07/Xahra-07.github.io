function drawFish(ctx, x, y, size, angle, time) {
  ctx.save();
  ctx.translate(x, y);
  ctx.rotate(angle);
  const isLight = document.body.classList.contains('light-theme');
  
  // Bioluminescent glowing shadow
  ctx.shadowBlur = 8;
  ctx.shadowColor = isLight ? 'rgba(160, 120, 16, 0.4)' : 'rgba(203, 161, 53, 0.5)';
  ctx.strokeStyle = isLight ? 'rgba(160, 120, 16, 0.35)' : 'rgba(203, 161, 53, 0.45)';
  ctx.lineWidth = 1.2;
  
  // Sleeker, organic body
  ctx.beginPath();
  ctx.moveTo(-size * 0.8, 0);
  ctx.quadraticCurveTo(0, -size * 0.35, size * 0.8, 0);
  ctx.quadraticCurveTo(0, size * 0.35, -size * 0.8, 0);
  ctx.stroke();
  
  // Elegant flowing dorsal fin
  ctx.beginPath();
  ctx.moveTo(-size * 0.2, -size * 0.25);
  ctx.quadraticCurveTo(size * 0.1, -size * 0.55, size * 0.3, -size * 0.15);
  ctx.stroke();
  
  // Flowing pelvic fin
  ctx.beginPath();
  ctx.moveTo(-size * 0.1, size * 0.25);
  ctx.quadraticCurveTo(size * 0.15, size * 0.45, size * 0.25, size * 0.18);
  ctx.stroke();
  
  // Silk-like split tail fin with organic wave movement
  const wiggle = Math.sin(time * 5.5) * 0.35;
  ctx.beginPath();
  ctx.moveTo(-size * 0.8, 0);
  ctx.bezierCurveTo(
    -size * 1.1, -size * 0.2 + wiggle * size * 0.5,
    -size * 1.3, -size * 0.5 + wiggle * size * 0.8,
    -size * 1.5, -size * 0.45 + wiggle * size
  );
  ctx.quadraticCurveTo(
    -size * 1.2, wiggle * size * 0.5,
    -size * 0.8, 0
  );
  
  ctx.bezierCurveTo(
    -size * 1.1, size * 0.2 + wiggle * size * 0.5,
    -size * 1.3, size * 0.5 + wiggle * size * 0.8,
    -size * 1.5, size * 0.45 + wiggle * size
  );
  ctx.quadraticCurveTo(
    -size * 1.2, wiggle * size * 0.5,
    -size * 0.8, 0
  );
  ctx.stroke();
  
  // Minimal eye
  ctx.beginPath();
  ctx.arc(size * 0.4, -size * 0.08, 1, 0, Math.PI * 2);
  ctx.fillStyle = isLight ? 'rgba(160, 120, 16, 0.4)' : 'rgba(203, 161, 53, 0.5)';
  ctx.fill();
  
  ctx.restore();
}

function drawJellyfish(ctx, x, y, size, time) {
  ctx.save();
  ctx.translate(x, y);
  const isLight = document.body.classList.contains('light-theme');
  
  ctx.shadowBlur = 8;
  ctx.shadowColor = isLight ? 'rgba(160, 120, 16, 0.4)' : 'rgba(203, 161, 53, 0.5)';
  ctx.strokeStyle = isLight ? 'rgba(160, 120, 16, 0.35)' : 'rgba(203, 161, 53, 0.45)';
  ctx.lineWidth = 1.2;
  
  const pulse = Math.sin(time * 2.0) * 0.08;
  const r = size * (1.0 + pulse);
  
  // 1. Draw outer bell dome (semi-circle cap, flat bottom line)
  ctx.beginPath();
  ctx.arc(0, 0, r, Math.PI, 0);
  ctx.closePath();
  ctx.stroke();
  
  // 2. Draw inner concentric bell dome (60% scale)
  ctx.beginPath();
  ctx.arc(0, 0, r * 0.6, Math.PI, 0);
  ctx.stroke();
  
  // 3. Draw vertical structural lines inside the bell dome
  const lineOffsets = [-0.3, 0, 0.3];
  lineOffsets.forEach(offset => {
    const lx = r * offset;
    const ly = -Math.sqrt(r * r - lx * lx);
    ctx.beginPath();
    ctx.moveTo(lx, ly);
    ctx.lineTo(lx, 0);
    ctx.stroke();
  });
  
  // 4. Draw 5 vertical wiggling tentacles hanging straight down
  const tentacleCount = 5;
  for (let i = 0; i < tentacleCount; i++) {
    const tx = -r * 0.7 + (r * 1.4 * i) / (tentacleCount - 1);
    ctx.beginPath();
    ctx.moveTo(tx, 0);
    
    let currX = tx;
    let currY = 0;
    const segments = 10;
    const segmentLen = size * 0.3;
    
    for (let j = 0; j < segments; j++) {
      const nextY = (j + 1) * segmentLen;
      // Gentle sine-wave wiggle downwards
      const wave = Math.sin(time * 3.0 - j * 0.5 + i * 1.0) * (size * 0.08);
      const nextX = tx + wave;
      ctx.quadraticCurveTo(currX, (currY + nextY) * 0.5, nextX, nextY);
      currX = nextX;
      currY = nextY;
    }
    ctx.stroke();
  }
  
  ctx.restore();
}

function drawBubbles() {
  bCtx.clearRect(0, 0, bCanvas.width, bCanvas.height);
  const isLight = document.body.classList.contains('light-theme');

  // Draw background creatures first so bubbles float in front
  creatures.forEach(c => {
    c.time += 0.015;
    c.x += c.speedX;
    c.y += c.speedY;

    if (c.type === 'fish') {
      if (c.speedX > 0 && c.x > window.innerWidth + c.size * 2) {
        c.x = -c.size * 2;
        c.y = Math.random() * window.innerHeight * 0.8 + window.innerHeight * 0.1;
      } else if (c.speedX < 0 && c.x < -c.size * 2) {
        c.x = window.innerWidth + c.size * 2;
        c.y = Math.random() * window.innerHeight * 0.8 + window.innerHeight * 0.1;
      }
      const angle = c.speedX > 0 ? 0 : Math.PI;
      drawFish(bCtx, c.x, c.y, c.size, angle, c.time);
    } else if (c.type === 'jellyfish') {
      if (c.y < -c.size * 2) {
        c.y = window.innerHeight + c.size * 2;
        c.x = Math.random() * window.innerWidth;
      }
      drawJellyfish(bCtx, c.x, c.y, c.size, c.time);
    }
  });

  // Update and draw bubbles
  for (let i = bubbles.length - 1; i >= 0; i--) {
    const b = bubbles[i];
    b.y -= b.speed;
    b.wobble += b.wobbleSpeed;
    b.x += Math.sin(b.wobble) * 0.3;

    if (b.isCursorBubble) {
      b.life -= b.decay;
      if (b.life <= 0) {
        bubbles.splice(i, 1);
        continue;
      }
    } else {
      if (b.y < -20) {
        b.y = bCanvas.height + 20;
        b.x = Math.random() * bCanvas.width;
      }
    }

    const fade = b.isCursorBubble ? b.life : Math.min(1, (bCanvas.height - b.y) / 150);
    
    bCtx.beginPath();
    bCtx.arc(b.x, b.y, b.r, 0, Math.PI * 2);
    bCtx.strokeStyle = isLight ? `rgba(1, 0, 102, ${b.opacity * fade})` : `rgba(203, 161, 53, ${b.opacity * fade})`;
    bCtx.lineWidth = 0.8;
    bCtx.stroke();

    bCtx.beginPath();
    bCtx.arc(b.x - b.r * 0.3, b.y - b.r * 0.3, b.r * 0.25, 0, Math.PI * 2);
    bCtx.fillStyle = `rgba(255, 255, 255, ${b.opacity * fade * 0.6})`;
    bCtx.fill();
  }

  requestAnimationFrame(drawBubbles);
}

drawBubbles();


