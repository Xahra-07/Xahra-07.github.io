// ── Dynamic Depth Indicator ──
const depthVal = document.getElementById('depth-val');
const depthMarker = document.querySelector('.depth-marker');
const depthIndicator = document.querySelector('.depth-indicator');
const footerEl = document.querySelector('footer');

window.addEventListener('scroll', () => {
  const maxScroll = document.documentElement.scrollHeight - window.innerHeight;
  const scrollPercent = maxScroll > 0 ? window.scrollY / maxScroll : 0;
  
  // Calculate depth down to 200 meters
  const depth = Math.round(scrollPercent * 200);
  depthVal.innerText = `${depth}m`;
  
  // Move indicator marker position
  depthMarker.style.top = `${scrollPercent * 100}%`;

  // Prevent depth indicator from overlaying the footer dynamically
  if (footerEl && depthIndicator) {
    const footerRect = footerEl.getBoundingClientRect();
    const indicatorHeight = 240;
    const viewportHeight = window.innerHeight;
    // Bottom boundary of indicator at top: 50% plus half the height + 40px buffer
    const indicatorBottom = (viewportHeight / 2) + (indicatorHeight / 2) + 40;
    
    if (footerRect.top < indicatorBottom) {
      const overlap = indicatorBottom - footerRect.top;
      depthIndicator.style.transform = `translateY(calc(-50% - ${overlap}px))`;
    } else {
      depthIndicator.style.transform = `translateY(-50%)`;
    }
  }
});

// ── Dynamic Track Selection Handler ──
let activeTrack = 'all';

function loadTrackContent(trackKey) {
  const data = TRACK_DATA[trackKey];
  if (!data) return;

  const experienceContainer = document.getElementById('experience-timeline');
  const skillsContainer = document.getElementById('skills-container');
  const credentialsContainer = document.getElementById('credentials-container');
  
  // Update Hero Titles with a dynamic text animation
  const titleText = document.getElementById('hero-title-text');
  const subtitleText = document.getElementById('hero-subtitle-text');
  const taglineText = document.getElementById('hero-tagline-text');
  
  // Fade out contents
  document.querySelectorAll('.dynamic-timeline, #skills-container, #tools-container, #credentials-container').forEach(el => {
    if (el) {
      el.style.opacity = '0';
      el.style.transform = 'translateY(15px)';
    }
  });
  
  setTimeout(() => {
    // Populate Hero text
    titleText.innerText = data.title;
    subtitleText.innerText = data.subtitle;
    taglineText.innerText = data.tagline;
    
    // Inject Experience items
    if (data.experience.length === 0) {
      experienceContainer.innerHTML = `<div class="timeline-empty card-glass">No experiences documented in this track.</div>`;
    } else {
      experienceContainer.innerHTML = data.experience.map(exp => `
        <div class="timeline-item card-glass">
          <div class="timeline-header">
            <div class="timeline-role-info">
              <h3>${exp.role}</h3>
              <span class="timeline-company">${exp.company}</span>
            </div>
            <span class="timeline-period">${exp.period}</span>
          </div>
          <ul class="timeline-desc">
            ${exp.bullets.map(b => `<li>${b}</li>`).join('')}
          </ul>
        </div>
      `).join('');
    }

    // Inject Skills cloud
    if (skillsContainer && data.skills) {
      skillsContainer.innerHTML = data.skills.map(skill => `
        <span class="skill-tag">${skill}</span>
      `).join('');
    }

    // Inject Tools cloud
    const toolsContainer = document.getElementById('tools-container');
    if (toolsContainer && data.tools) {
      toolsContainer.innerHTML = data.tools.map(tool => `
        <span class="skill-tag">${tool}</span>
      `).join('');
    }

    // Inject Credentials list
    if (credentialsContainer && data.certifications) {
      credentialsContainer.innerHTML = data.certifications.map(cred => `
        <div class="credential-item">
          <h4 class="cred-title">${cred.title}</h4>
          <span class="cred-issuer">
            ${cred.issuer}
            ${cred.verify ? `<span class="verify-tag">[${cred.verify}]</span>` : ''}
          </span>
        </div>
      `).join('');
    }
    
    // Inject Projects in Timeline if present
    if (data.projects && data.projects.length > 0) {
      experienceContainer.innerHTML += `
        <div style="margin-top: 40px;">
          <h3 style="margin-bottom: 24px; color: var(--gold);">Projects & Community Impact</h3>
          <div class="projects-grid-list">
            ${data.projects.map(proj => `
              <div class="timeline-item card-glass" style="border-left: 2px solid var(--gold); margin-bottom: 0;">
                <span class="timeline-company" style="font-size: 11px; text-transform: uppercase; letter-spacing: 0.1em; display: block; margin-bottom: 6px;">${proj.org}</span>
                <h4 style="font-size: 18px; color: var(--white); margin-bottom: 8px;">${proj.title}</h4>
                <p style="font-size: 14px; line-height: 1.6;">${proj.desc}</p>
              </div>
            `).join('')}
          </div>
        </div>
      `;
    }

    // Fade back in
    document.querySelectorAll('.dynamic-timeline, #skills-container, #tools-container, #credentials-container').forEach(el => {
      if (el) {
        el.style.opacity = '1';
        el.style.transform = 'translateY(0)';
        el.style.transition = 'opacity 0.6s cubic-bezier(0.16, 1, 0.3, 1), transform 0.6s cubic-bezier(0.16, 1, 0.3, 1)';
      }
    });
  }, 400);
}

